"""Fit the how-to explainer to its voice-over, then mix voice + music.

  python3 voiceover-video.py timing        writes explainer-timing.js (stretches each section to fit its line)
  node render.cjs how-to-use-explainer.html out/WeeSubby-HowToUse-voice-silent.mp4
  python3 voiceover-video.py mix out/WeeSubby-HowToUse-voice-silent.mp4 out/WeeSubby-HowToUse-voice.mp4

Each script line starts LEAD seconds into its section. A section that is too short for its line plus a
TAIL pause is slowed down evenly (animations keep their order, just play slower); longer sections are
left as they are. Music (track from music.txt for WeeSubby-HowToUse.mp4) sits well under the voice.
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LEAD, TAIL = 0.4, 0.6
# Section boundaries in the explainer's own timeline (seconds), matching the step windows in the page.
SECTIONS = [('intro', 0, 4.7), ('h1', 4.7, 12.5), ('h2', 12.5, 22), ('h3', 22, 31), ('h4', 31, 43.5),
            ('h5', 43.5, 53), ('mid', 53, 56.7), ('c1', 56.7, 67), ('c2', 67, 73), ('c3', 73, 81),
            ('c4', 81, 92), ('c5', 92, 99), ('outro', 99, 104)]


def dur(path):
    return float(subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', path],
                                capture_output=True, text=True, check=True).stdout)


def plan():
    out, warp, starts = 0.0, [], {}
    for seg, a, b in SECTIONS:
        need = LEAD + dur(os.path.join(HERE, 'voiceover', f'{seg}.mp3')) + TAIL
        length = max(b - a, round(need, 2))
        warp.append([a, b, round(out, 3), round(out + length, 3)])
        starts[seg] = out + LEAD
        out += length
    return warp, starts, out


cmd = sys.argv[1] if len(sys.argv) > 1 else ''
warp, starts, total = plan()
if cmd == 'timing':
    with open(os.path.join(HERE, 'explainer-timing.js'), 'w') as f:
        f.write('// Generated by voiceover-video.py: [srcStart, srcEnd, outStart, outEnd] per section.\n')
        f.write(f'window.WARP = {json.dumps(warp)};\n')
    for (seg, a, b), w in zip(SECTIONS, warp):
        print(f'{seg:6} {b - a:5.1f}s -> {w[3] - w[2]:5.2f}s')
    print(f'total {total:.2f}s')
elif cmd == 'mix':
    video, out = sys.argv[2], sys.argv[3]
    track, start = next(l.split()[1:] for l in open(os.path.join(HERE, 'music.txt'))
                        if l.startswith('WeeSubby-HowToUse.mp4'))
    music = os.path.join(HERE, 'music', f'{track}.mp3')
    if not os.path.exists(music):
        os.makedirs(os.path.dirname(music), exist_ok=True)
        subprocess.run(['curl', '-fsS', '-o', music, f'https://assets.mixkit.co/music/{track}/{track}.mp3'], check=True)
    inputs, chains, labels = ['-i', video, '-ss', start, '-t', f'{total:.3f}', '-i', music], [], []
    for i, (seg, _, _) in enumerate(SECTIONS):
        inputs += ['-i', os.path.join(HERE, 'voiceover', f'{seg}.mp3')]
        ms = int(starts[seg] * 1000)
        chains.append(f'[{i + 2}:a]aresample=48000,adelay={ms}|{ms}[v{i}]')
        labels.append(f'[v{i}]')
    fade = total - 3.5
    graph = ';'.join(chains + [
        f'{"".join(labels)}amix=inputs={len(labels)}:normalize=0,loudnorm=I=-16:TP=-2[voice]',
        f'[1:a]aresample=48000,afade=t=in:d=0.5,afade=t=out:st={fade:.2f}:d=3.5,loudnorm=I=-30:TP=-9[bed]',
        '[voice][bed]amix=inputs=2:normalize=0:duration=longest,loudnorm=I=-14:TP=-1.5:LRA=11,aresample=48000[a]'])
    subprocess.run(['ffmpeg', '-nostdin', '-loglevel', 'error', '-y', *inputs, '-filter_complex', graph,
                    '-map', '0:v', '-map', '[a]', '-c:v', 'copy', '-c:a', 'aac', '-b:a', '192k', '-ac', '2',
                    '-t', f'{total:.3f}', '-movflags', '+faststart', out], check=True)
    print('wrote', out)
else:
    sys.exit(__doc__)
